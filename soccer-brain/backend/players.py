"""Player store + importer.

`data/players.json` is Soccer Brain's internal store. It is built from the curated master
list (the site's players.json) and keeps per-field provenance:

* `master-list` fields are refreshed when the master list changes.
* `manual` (edited in the studio) and `verified` (data/verified-facts.json) fields are
  never overwritten by a re-import; a differing master-list value is reported as a conflict.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
import shutil
import threading
import unicodedata
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from .config import settings
from .models import Achievement, CareerStint, ClubBadge, ImageCredit, Player, Provenance, today

log = logging.getLogger(__name__)

_lock = threading.RLock()

HONOR_KEYS = {"wc": "world_cup", "cl": "champions_league", "bo": "ballon_dor", "co": "continental"}

# Continental national-team competition by country code (matches the site's labelling).
CONFEDERATION_CUP = {
    **{c: "Copa América" for c in ["AR", "BR", "UY", "CO", "CL", "PE", "PY", "EC", "BO", "VE"]},
    **{c: "Gold Cup" for c in ["US", "MX", "CA", "CR", "JM", "HN", "PA"]},
    **{c: "Africa Cup of Nations" for c in ["EG", "SN", "MA", "CM", "NG", "CI", "GH", "DZ", "CV", "LR"]},
    **{c: "Asian Cup" for c in ["KR", "JP", "SA", "QA", "IR", "AU"]},
}

TRACKED_FIELDS = [
    "name",
    "country",
    "country_code",
    "current_club",
    "career_clubs",
    "career_timeline",
    "retired",
    "position",
    "dob",
    "died",
    "jersey_number",
    "fun_fact",
]


def slugify(name: str) -> str:
    name = re.sub(r"\(.*?\)", "", name)
    s = unicodedata.normalize("NFKD", name.replace("ø", "o").replace("Ø", "O"))
    s = s.encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def display_name(name: str) -> str:
    """'Ronaldo Nazário (R9)' -> 'Ronaldo Nazário'."""
    return re.sub(r"\s*\(.*?\)\s*", " ", name).strip()


def continental_label(country_code: str) -> str:
    cc = country_code.upper()
    if cc in CONFEDERATION_CUP:
        return CONFEDERATION_CUP[cc]
    return "Euros"


# --------------------------------------------------------------------------- store


def _store_path() -> Path:
    return settings.data_dir / "players.json"


def load_players() -> list[Player]:
    p = _store_path()
    if not p.exists():
        return []
    raw = json.loads(p.read_text())
    return [Player.model_validate(x) for x in raw["players"]]


def save_players(players: list[Player]) -> None:
    with _lock:
        p = _store_path()
        p.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "_comment": "Generated by `soccer-brain import` from the master list, plus studio edits. See backend/players.py.",
            "updatedAt": today(),
            "players": [x.model_dump(by_alias=True, exclude_none=True, mode="json") for x in sorted(players, key=lambda x: x.name)],
        }
        tmp = p.with_suffix(".tmp")
        tmp.write_text(json.dumps(data, indent=1, ensure_ascii=False))
        tmp.replace(p)


def players_by_id() -> dict[str, Player]:
    return {p.id: p for p in load_players()}


def get_player(pid: str) -> Player | None:
    return players_by_id().get(pid)


def upsert_player(player: Player, *, manual_fields: list[str] | None = None) -> Player:
    """Save a player edited in the studio. Edited fields become `manual` provenance."""
    with _lock:
        players = load_players()
        for f in manual_fields or []:
            player.provenance[f] = Provenance(source="manual", updatedAt=today())
        players = [p for p in players if p.id != player.id] + [player]
        save_players(players)
    return player


def confirm_current_club(pid: str, club: str | None) -> Player:
    with _lock:
        p = get_player(pid)
        if not p:
            raise KeyError(pid)
        if club is not None and club != p.current_club:
            p.current_club = club
            p.provenance["current_club"] = Provenance(source="manual", updatedAt=today())
        p.current_club_verified_at = today()
        return upsert_player(p)


def current_club_is_fresh(p: Player) -> bool:
    if p.retired or not p.current_club or not p.current_club_verified_at:
        return False
    age = (date.today() - date.fromisoformat(p.current_club_verified_at)).days
    return age <= settings.current_club_max_age_days


# ------------------------------------------------------------------------- clubs


def parse_clubs_js(js_path: Path) -> dict[str, ClubBadge]:
    """Read the site's CLUBS colour map out of players.js."""
    if not js_path.exists():
        return {}
    text = js_path.read_text()
    m = re.search(r"const CLUBS\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        return {}
    out: dict[str, ClubBadge] = {}
    for name, body in re.findall(r'"([^"]+)"\s*:\s*\{([^}]*)\}', m.group(1)):
        kv = dict(re.findall(r'(\w+)\s*:\s*"([^"]*)"', body))
        if {"c1", "c2", "ab", "ink"} <= kv.keys():
            out[name] = ClubBadge(name=name, short=kv["ab"], c1=kv["c1"], c2=kv["c2"], ink=kv["ink"])
    return out


def load_clubs() -> dict[str, ClubBadge]:
    p = settings.data_dir / "clubs.json"
    if not p.exists():
        return {}
    return {k: ClubBadge.model_validate(v) for k, v in json.loads(p.read_text()).items()}


def club_badge(name: str | None, clubs: dict[str, ClubBadge] | None = None) -> ClubBadge | None:
    if not name:
        return None
    clubs = clubs if clubs is not None else load_clubs()
    if name in clubs:
        return clubs[name]
    # Fallback: neutral colours + initials (never a real crest).
    letters = "".join(w[0] for w in re.findall(r"[A-Za-zÀ-ÿ]+", name) if w[0].isupper())[:3] or name[:3].upper()
    return ClubBadge(name=name, short=letters.upper(), c1="#1d3b2a", c2="#e9f2ec", ink="#ffffff")


# ------------------------------------------------------------------------ images


def image_rel_path(pid: str) -> str:
    """Hash-named so the file name can never leak the answer."""
    return f"img/{hashlib.sha1(f'sb-img|{pid}'.encode()).hexdigest()[:12]}.jpg"


def commons_filename(url: str) -> str | None:
    m = re.search(r"Special:FilePath/([^?]+)", url) or re.search(r"/wikipedia/commons/(?:thumb/)?[0-9a-f]/[0-9a-f]{2}/([^/?]+)", url)
    if not m:
        return None
    from urllib.parse import unquote

    return unquote(m.group(1))


_UA = {"User-Agent": "SoccerBrainStudio/1.0 (local trivia video tool; contact via repo owner)"}


def _polite_get(url: str, **kw):
    """GET with a gap between requests and backoff on Wikimedia rate limits (403/429)."""
    import time

    import httpx

    for attempt in range(4):
        time.sleep(0.7 if attempt == 0 else 4 * attempt)
        r = httpx.get(url, follow_redirects=True, timeout=30, headers=_UA, **kw)
        if r.status_code not in (403, 429, 503):
            r.raise_for_status()
            return r
        log.info("rate limited (%s) on %s, retrying", r.status_code, url)
    r.raise_for_status()
    return r


def _download(url: str, dest: Path) -> bool:

    fname = commons_filename(url)
    if fname:
        url = f"https://commons.wikimedia.org/wiki/Special:FilePath/{fname}?width=800"
    try:
        r = _polite_get(url)
        if not r.headers.get("content-type", "").startswith("image/"):
            return False
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(r.content)
        return True
    except Exception as e:  # network failures fall back to the jersey graphic
        log.warning("image download failed %s: %s", url, e)
        return False


def fetch_commons_credit(filename: str) -> ImageCredit | None:
    try:
        r = _polite_get(
            "https://commons.wikimedia.org/w/api.php",
            params={"action": "query", "titles": f"File:{filename}", "prop": "imageinfo", "iiprop": "extmetadata", "format": "json"},
        )
        page = next(iter(r.json()["query"]["pages"].values()))
        meta = page["imageinfo"][0]["extmetadata"]
        artist = re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", "")).strip() or None
        return ImageCredit(
            author=artist,
            license=meta.get("LicenseShortName", {}).get("value"),
            licenseUrl=meta.get("LicenseUrl", {}).get("value"),
            sourceUrl=f"https://commons.wikimedia.org/wiki/File:{filename.replace(' ', '_')}",
        )
    except Exception as e:
        log.warning("credit lookup failed for %s: %s", filename, e)
        return None


# ------------------------------------------------------------------------ import


@dataclass
class ImportReport:
    added: list[str] = field(default_factory=list)
    updated: dict[str, list[str]] = field(default_factory=dict)
    conflicts: list[dict] = field(default_factory=list)
    unchanged: int = 0
    images_copied: int = 0
    images_missing: list[str] = field(default_factory=list)
    credits_missing: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    def summary(self) -> str:
        return (
            f"added={len(self.added)} updated={len(self.updated)} unchanged={self.unchanged} "
            f"conflicts={len(self.conflicts)} images={self.images_copied} no_image={len(self.images_missing)} "
            f"no_credit={len(self.credits_missing)} errors={len(self.errors)}"
        )


def _from_source(raw: dict) -> dict:
    """Map one master-list record to Player field values (snake_case)."""
    retired = str(raw.get("currentClub", "")).strip().lower().startswith("retired")
    timeline = [CareerStint(club=t["club"], years=t.get("years")) for t in raw.get("careerTimeline", []) if t.get("club")]
    return {
        "name": raw["name"].strip(),
        "country": raw["country"].strip(),
        "country_code": raw["countryCode"].strip().upper(),
        "current_club": None if retired else (raw.get("currentClub") or None),
        "career_clubs": [c.strip() for c in raw.get("clubs", []) if c and c.strip()],
        "career_timeline": timeline,
        "retired": retired,
        "position": raw.get("pos") if raw.get("pos") in ("GK", "DEF", "MID", "FWD") else None,
        "dob": raw.get("dob") or None,
        "died": raw.get("died") or None,
        "jersey_number": raw.get("jerseyNumber") if isinstance(raw.get("jerseyNumber"), int) else None,
        "fun_fact": raw.get("funFact") or None,
    }


def _span_years(years: str | None) -> int | None:
    if not years:
        return None
    m = re.match(r"(\d{4})\s*[-–]\s*(\d{4})?", years)
    if not m:
        return None
    end = int(m.group(2)) if m.group(2) else date.today().year
    return end - int(m.group(1))


def derive_primary_club(timeline: list[CareerStint], clubs: list[str]) -> str | None:
    """Longest single club tenure from the dated timeline; or the only club."""
    if len(set(clubs)) == 1:
        return clubs[0]
    totals: dict[str, int] = {}
    for t in timeline:
        y = _span_years(t.years)
        if y is not None:
            totals[t.club] = totals.get(t.club, 0) + y
    if not totals:
        return None
    best = sorted(totals.items(), key=lambda kv: -kv[1])
    if len(best) > 1 and best[0][1] == best[1][1]:
        return None  # tie: don't guess
    return best[0][0]


def _achievements(raw: dict, cc: str, existing: list[Achievement]) -> list[Achievement]:
    by_type = {a.type: a for a in existing}
    out: list[Achievement] = []
    for key, typ in HONOR_KEYS.items():
        count = int((raw.get("honors") or {}).get(key, 0) or 0)
        prev = by_type.get(typ)
        if prev and prev.provenance.source in ("manual", "verified"):
            out.append(prev)
            continue
        if count <= 0:
            continue
        out.append(
            Achievement(
                type=typ,
                count=count,
                years=[],  # derived years are recomputed below; curated ones are kept above
                label=continental_label(cc) if typ == "continental" else None,
                provenance=Provenance(source="master-list", updatedAt=today()),
            )
        )
    return out


def _apply_verified(p: Player, facts: dict) -> None:
    f = facts.get(p.name) or facts.get(p.id)
    if not f:
        return
    for typ, spec in (f.get("achievements") or {}).items():
        ach = p.achievement(typ)
        years = sorted(spec.get("years", []))
        if ach and ach.count == len(years):
            ach.years = years
            ach.provenance = Provenance(source="verified", sourceUrl=spec.get("sourceUrl"), verifiedAt=spec.get("verifiedAt"))
        elif ach:
            log.warning("verified %s years for %s (%d) disagree with count %d; not applied", typ, p.name, len(years), ach.count)
    if "category" in f:
        p.category = f["category"]["value"]
    if "primaryClub" in f:
        p.primary_club = f["primaryClub"]["value"]
        p.provenance["primary_club"] = Provenance(source="verified", sourceUrl=f["primaryClub"].get("sourceUrl"), verifiedAt=f["primaryClub"].get("verifiedAt"))


def _tenures(p: Player) -> dict[str, list[tuple[int, int]]]:
    """club -> [(start_year, end_year)] from the dated career timeline (open end = this year)."""
    out: dict[str, list[tuple[int, int]]] = {}
    for t in p.career_timeline:
        m = re.match(r"(\d{4})\s*[-–]\s*(\d{4})?", t.years or "")
        if m:
            out.setdefault(t.club, []).append((int(m.group(1)), int(m.group(2)) if m.group(2) else date.today().year))
    return out


def derive_trophy_years(p: Player, winners: dict) -> None:
    """Fill in WHICH years a player won the World Cup / Champions League.

    Candidates come from the official winners lists, filtered by the player's country (World Cup)
    or career clubs and dated tenures (Champions League), and an age window of 17-41. Years are
    only recorded when the number of candidates equals the curated count exactly; otherwise the
    clue stays count-only ("I won the Champions League!") rather than guessing.
    """
    if not p.dob:
        return
    born = int(p.dob[:4])
    died = int(p.died[:4]) if p.died else 9999
    aliases = winners.get("aliases", {})

    def norm(name: str) -> str:
        return aliases.get(name, name)

    def plausible(year: int) -> bool:
        return 17 <= year - born <= 41 and year <= died

    def apply(kind: str, years: list[int], src: str) -> None:
        a = p.achievement(kind)
        if not a or a.provenance.source in ("manual", "verified") or a.years:
            return
        if len(years) == a.count:
            a.years = sorted(years)
            a.provenance = Provenance(source="derived", detail=f"years matched against the winners list ({a.count} of {a.count})", sourceUrl=src)

    wc_key = "womens_world_cup" if p.category == "women" else "world_cup"
    wc = winners.get(wc_key, {})
    country = norm(p.country)
    years = [int(y) for y, w in wc.get("winners", {}).items() if norm(w) == country and plausible(int(y))]
    apply("world_cup", years, wc.get("sourceUrl"))

    if p.category == "men":
        cl = winners.get("champions_league", {})
        tenure = _tenures(p)
        clubs = set(p.career_clubs)
        years = []
        for y, w in cl.get("winners", {}).items():
            year, club = int(y), norm(w)
            if club not in clubs or not plausible(year):
                continue
            spans = tenure.get(club)
            if spans and not any(start < year <= end for start, end in spans):
                continue  # known to have been elsewhere that season
            years.append(year)
        apply("champions_league", years, cl.get("sourceUrl"))


def import_master_list(*, download_images: bool = True, fetch_credits: bool = True) -> ImportReport:
    """Import / refresh from the master list without clobbering curated edits."""
    report = ImportReport()
    raw_players = json.loads(settings.master_list.read_text())
    if isinstance(raw_players, dict):
        raw_players = raw_players.get("players", [])
    facts_path = settings.data_dir / "verified-facts.json"
    facts = json.loads(facts_path.read_text()).get("players", {}) if facts_path.exists() else {}
    winners_path = settings.data_dir / "competition-winners.json"
    winners = json.loads(winners_path.read_text()) if winners_path.exists() else {}

    clubs = parse_clubs_js(settings.master_js)
    clubs_path = settings.data_dir / "clubs.json"
    existing_clubs = json.loads(clubs_path.read_text()) if clubs_path.exists() else {}
    merged_clubs = {**{k: v.model_dump() for k, v in clubs.items()}, **{k: v for k, v in existing_clubs.items() if k not in clubs}}
    clubs_path.parent.mkdir(parents=True, exist_ok=True)
    clubs_path.write_text(json.dumps(merged_clubs, indent=1, ensure_ascii=False))

    credits_path = settings.data_dir / "image-credits.json"
    credits: dict = json.loads(credits_path.read_text()) if credits_path.exists() else {}

    existing = {p.id: p for p in load_players()}
    result: list[Player] = []
    seen: set[str] = set()

    for raw in raw_players:
        try:
            vals = _from_source(raw)
        except (KeyError, AttributeError, TypeError) as e:
            report.errors.append(f"bad record {raw.get('name', '?')}: {e}")
            continue
        pid = slugify(vals["name"])
        if pid in seen:
            report.errors.append(f"duplicate id {pid}")
            continue
        seen.add(pid)
        prev = existing.get(pid)
        if prev is None:
            p = Player(id=pid, **vals)
            for k in TRACKED_FIELDS:
                p.provenance[k] = Provenance(source="master-list", updatedAt=today())
            report.added.append(pid)
        else:
            p = prev.model_copy(deep=True)
            changed = []
            for k, v in vals.items():
                cur = getattr(p, k)
                if cur == v:
                    continue
                prov = p.provenance.get(k)
                if prov and prov.source in ("manual", "verified"):
                    report.conflicts.append({"player": pid, "field": k, "kept": _jsonable(cur), "masterList": _jsonable(v)})
                    continue
                setattr(p, k, v)
                p.provenance[k] = Provenance(source="master-list", updatedAt=today())
                changed.append(k)
                if k == "current_club":
                    p.current_club_verified_at = None  # club changed: needs re-confirmation
            if changed:
                report.updated[pid] = changed
            else:
                report.unchanged += 1

        p.achievements = _achievements(raw, p.country_code, p.achievements)
        prov = p.provenance.get("primary_club")
        if not (prov and prov.source in ("manual", "verified")):
            derived = derive_primary_club(p.career_timeline, p.career_clubs)
            p.primary_club = derived
            if derived:
                p.provenance["primary_club"] = Provenance(source="derived", detail="longest tenure in careerTimeline")
            else:
                p.provenance.pop("primary_club", None)
        _apply_verified(p, facts)
        derive_trophy_years(p, winners)

        # Image: copy local file / download Commons file to a hash-named path.
        img_url = (raw.get("imageUrl") or "").strip()
        rel = image_rel_path(pid)
        dest = settings.public_dir / rel
        if img_url:
            ok = dest.exists()
            if not ok and img_url.startswith("assets/"):
                srcf = settings.master_assets.parent / img_url
                if srcf.exists():
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(srcf, dest)
                    ok = True
            elif not ok and download_images and img_url.startswith("http"):
                ok = _download(img_url, dest)
            if ok:
                p.image_path = rel
                report.images_copied += 1
            else:
                p.image_path = None
                report.images_missing.append(pid)
        else:
            p.image_path = None
            report.images_missing.append(pid)

        if p.image_path:
            fname = commons_filename(img_url) if img_url.startswith("http") else None
            if pid in credits:
                p.image_credit = ImageCredit.model_validate(credits[pid])
            elif fname and fetch_credits:
                c = fetch_commons_credit(fname)
                if c:
                    credits[pid] = c.model_dump(by_alias=True, exclude_none=True)
                    p.image_credit = c
            if not p.image_credit:
                report.credits_missing.append(pid)

        result.append(p)

    # Keep players that were added manually in the studio (not in the master list).
    for pid, p in existing.items():
        if pid not in seen and p.provenance.get("name", Provenance(source="manual")).source == "manual":
            result.append(p)

    credits_path.write_text(json.dumps(dict(sorted(credits.items())), indent=1, ensure_ascii=False))
    save_players(result)
    report_path = settings.data_dir / "last-import-report.json"
    report_path.write_text(json.dumps(report.__dict__, indent=1, ensure_ascii=False, default=str))
    log.info("import %s", report.summary())
    return report


def _jsonable(v):
    if isinstance(v, list):
        return [x.model_dump() if hasattr(x, "model_dump") else x for x in v]
    return v
